package com.datasphere.migration.project;

import com.datasphere.migration.db.ConnectionProfile;
import com.datasphere.migration.db.ConnectionRole;
import com.datasphere.migration.db.DatabaseType;
import com.datasphere.migration.exception.ApplicationException;
import com.datasphere.migration.exception.ErrorCode;
import com.datasphere.migration.mapping.engine.MappingEngine;
import com.datasphere.migration.mapping.engine.ScoreBreakdown;
import com.datasphere.migration.mapping.model.ColumnMapping;
import com.datasphere.migration.mapping.model.MappingStatus;
import com.datasphere.migration.mapping.type.CompatibilityLevel;
import com.datasphere.migration.mapping.type.Transformation;
import com.datasphere.migration.mapping.type.TypeNormalizer;
import com.datasphere.migration.mapping.validation.MappingValidator;
import com.datasphere.migration.metadata.ColumnMetadata;
import com.datasphere.migration.metadata.TableMetadata;
import java.time.Instant;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Service;

/**
 * The mapping review workflow: suggest, edit, validate, approve. Every change increments the mapping version
 * and withdraws any earlier approval, so approval always refers to exactly the mapping the user last reviewed.
 */
@Service
public class MappingWorkflowService {

    private static final Logger audit = LoggerFactory.getLogger("com.datasphere.migration.audit.mapping");

    private final ProjectService projects;
    private final DiscoveryService discovery;
    private final MappingEngine engine;
    private final MappingValidator validator;

    public MappingWorkflowService(ProjectService projects, DiscoveryService discovery, MappingEngine engine,
                                  MappingValidator validator) {
        this.projects = projects;
        this.discovery = discovery;
        this.engine = engine;
        this.validator = validator;
    }

    // ------------------------------------------------------------------ suggestions

    /**
     * Generates mapping suggestions for every selected table pair and puts the project into
     * {@code MAPPING_REVIEW_REQUIRED}. Nothing is approved and nothing is migrated.
     *
     * @param overwrite must be true to replace mappings the user has already reviewed
     */
    public MigrationProject suggest(String projectId, boolean overwrite) {
        return projects.modify(projectId, project -> {
            if (project.getTablePairs().isEmpty()) {
                throw state("Select the tables to migrate before generating suggestions.");
            }
            if (!overwrite && hasUserDecisions(project)) {
                throw state("Mappings you already reviewed would be replaced. Confirm the overwrite to continue.");
            }
            for (TablePairMapping pair : project.getTablePairs()) {
                suggestPair(project, pair);
            }
            project.bumpVersion();
            project.invalidateApproval();
            project.setLastValidation(null);
            project.transition(ProjectState.SUGGESTIONS_GENERATED, "Suggestions generated by the mapping engine");
            project.transition(ProjectState.MAPPING_REVIEW_REQUIRED, "Mapping must be reviewed by the user");
            projects.save(project);
            audit.info("Suggestions generated project={} version={} pairs={}", projectId, project.getMappingVersion(),
                    project.getTablePairs().size());
            return project;
        });
    }

    private void suggestPair(MigrationProject project, TablePairMapping pair) {
        TableMetadata source = snapshot(project, ConnectionRole.SOURCE, pair);
        TableMetadata target = snapshot(project, ConnectionRole.TARGET, pair);
        pair.setColumns(engine.suggest(source, target, dbType(project, ConnectionRole.SOURCE),
                dbType(project, ConnectionRole.TARGET)));
    }

    private static boolean hasUserDecisions(MigrationProject project) {
        return project.getTablePairs().stream().flatMap(p -> p.getColumns().stream())
                .anyMatch(c -> ColumnMapping.ORIGIN_USER.equals(c.getOrigin())
                        || c.getStatus() == MappingStatus.ACCEPTED || c.getStatus() == MappingStatus.REJECTED
                        || c.getStatus() == MappingStatus.MODIFIED);
    }

    // ------------------------------------------------------------------ editing

    public MigrationProject applyChanges(String projectId, MappingChangeRequest request) {
        return projects.modify(projectId, project -> {
            if (request.expectedVersion() != project.getMappingVersion()) {
                throw new ApplicationException(ErrorCode.PRJ_CONFLICT_001, "Expected version "
                        + request.expectedVersion() + " but project is at " + project.getMappingVersion());
            }
            if (project.getState() == ProjectState.MIGRATING) {
                throw state("The mapping cannot be changed while a migration is running.");
            }
            if (!project.hasMappings()) {
                throw state("Generate mapping suggestions before editing the mapping.");
            }
            boolean wasApproved = project.getApproval() != null;
            for (MappingChangeRequest.Change change : request.changes()) {
                apply(project, change);
            }
            project.bumpVersion();
            project.invalidateApproval();
            project.setLastValidation(null);
            project.transition(ProjectState.MAPPING_MODIFIED, wasApproved
                    ? "Mapping changed after approval; the approval was withdrawn" : "Mapping edited by the user");
            projects.save(project);
            audit.info("Mapping edited project={} version={} changes={} approvalWithdrawn={}", projectId,
                    project.getMappingVersion(), request.changes().size(), wasApproved);
            return project;
        });
    }

    private void apply(MigrationProject project, MappingChangeRequest.Change change) {
        switch (change.action()) {
            case ACCEPT_ALL_SUGGESTED -> acceptAllSuggested(project, change.pairId());
            case RESET_PAIR -> suggestPair(project, requirePair(project, change.pairId()));
            default -> applyToColumn(project, change);
        }
    }

    private void acceptAllSuggested(MigrationProject project, String pairId) {
        for (TablePairMapping pair : project.getTablePairs()) {
            if (pairId != null && !pairId.isBlank() && !pair.getId().equals(pairId)) {
                continue;
            }
            for (ColumnMapping m : pair.getColumns()) {
                if (m.getStatus() == MappingStatus.SUGGESTED) {
                    m.setStatus(MappingStatus.ACCEPTED);
                    m.setDecidedAt(Instant.now());
                }
            }
        }
    }

    private void applyToColumn(MigrationProject project, MappingChangeRequest.Change change) {
        TablePairMapping pair = requirePair(project, change.pairId());
        ColumnMapping m = pair.columnFor(change.sourceColumn()).orElseThrow(() ->
                invalid("The source column '" + change.sourceColumn() + "' is not part of this table pair."));
        TableMetadata source = snapshot(project, ConnectionRole.SOURCE, pair);
        TableMetadata target = snapshot(project, ConnectionRole.TARGET, pair);
        DatabaseType sourceDb = dbType(project, ConnectionRole.SOURCE);
        DatabaseType targetDb = dbType(project, ConnectionRole.TARGET);

        switch (change.action()) {
            case ACCEPT -> {
                if (!m.isMapped()) {
                    throw invalid("Choose a target column for " + m.getSourceColumn() + " before accepting it.");
                }
                if (m.getCompatibility() == CompatibilityLevel.INCOMPATIBLE) {
                    throw invalid(m.getSourceColumn() + " \u2192 " + m.getTargetColumn() + " has incompatible data "
                            + "types. Choose a conversion or a different target first.");
                }
                m.setStatus(MappingStatus.ACCEPTED);
                m.setDecidedAt(Instant.now());
            }
            case REJECT -> {
                if (m.isMapped()) {
                    m.setRejectedTarget(m.getTargetColumn());
                }
                clear(m, MappingStatus.REJECTED, "You rejected the suggestion"
                        + (m.getRejectedTarget() == null ? "" : " " + m.getRejectedTarget())
                        + ". This column will not be migrated unless you choose a target.");
            }
            case CLEAR -> clear(m, MappingStatus.UNMAPPED,
                    "You left this column unmapped. Its data will not be migrated.");
            case SET_TARGET -> {
                if (change.targetColumn() == null || change.targetColumn().isBlank()) {
                    clear(m, MappingStatus.UNMAPPED, "You left this column unmapped. Its data will not be migrated.");
                } else {
                    setTarget(m, source, target, change.targetColumn(), sourceDb, targetDb);
                }
            }
            case SET_TRANSFORMATION -> setTransformation(m, source, target, change, sourceDb, targetDb);
            default -> throw invalid("Unsupported action.");
        }
    }

    private void clear(ColumnMapping m, MappingStatus status, String reason) {
        m.setTargetColumn(null);
        m.setStatus(status);
        m.setTransformation(Transformation.NONE);
        m.setTransformationParameter(null);
        m.setCompatibility(null);
        m.setScore(0);
        m.setReasons(List.of(reason));
        m.setWarnings(List.of());
        m.setOrigin(ColumnMapping.ORIGIN_USER);
        m.setDecidedAt(Instant.now());
    }

    private void setTarget(ColumnMapping m, TableMetadata source, TableMetadata target, String targetName,
                           DatabaseType sourceDb, DatabaseType targetDb) {
        ColumnMetadata sourceColumn = source.column(m.getSourceColumn()).orElseThrow(() ->
                invalid("The source column '" + m.getSourceColumn() + "' no longer exists."));
        ColumnMetadata targetColumn = target.column(targetName).orElseThrow(() ->
                invalid("The target column '" + targetName + "' does not exist in " + target.ref().key() + "."));
        m.setTargetColumn(targetColumn.name());
        m.setTransformation(Transformation.NONE);
        m.setTransformationParameter(null);
        rescore(m, sourceColumn, targetColumn, sourceDb, targetDb);
        List<String> reasons = new ArrayList<>(m.getReasons());
        reasons.add(0, "You chose this target column manually.");
        m.setReasons(reasons);
        m.setStatus(MappingStatus.MODIFIED);
        m.setOrigin(ColumnMapping.ORIGIN_USER);
        m.setDecidedAt(Instant.now());
    }

    private void setTransformation(ColumnMapping m, TableMetadata source, TableMetadata target,
                                   MappingChangeRequest.Change change, DatabaseType sourceDb, DatabaseType targetDb) {
        if (!m.isMapped()) {
            throw invalid("Choose a target column before choosing a conversion.");
        }
        Transformation transformation;
        try {
            transformation = Transformation.valueOf(String.valueOf(change.transformation()));
        } catch (IllegalArgumentException e) {
            throw invalid("Unknown conversion.");
        }
        ColumnMetadata sourceColumn = source.column(m.getSourceColumn()).orElseThrow(() ->
                invalid("The source column '" + m.getSourceColumn() + "' no longer exists."));
        ColumnMetadata targetColumn = target.column(m.getTargetColumn()).orElseThrow(() ->
                invalid("The target column '" + m.getTargetColumn() + "' no longer exists."));
        var sourceCategory = TypeNormalizer.normalize(sourceColumn, sourceDb).category();
        var targetCategory = TypeNormalizer.normalize(targetColumn, targetDb).category();
        if (!transformation.isApplicable(sourceCategory, targetCategory)) {
            throw invalid("The conversion '" + transformation.label() + "' cannot turn "
                    + sourceCategory.plainName() + " into " + targetCategory.plainName() + ".");
        }
        String parameter = change.transformationParameter() == null || change.transformationParameter().isBlank()
                ? null : change.transformationParameter().trim();
        Optional<String> problem = transformation.validateParameter(parameter, targetCategory);
        if (problem.isPresent()) {
            throw invalid(problem.get());
        }
        m.setTransformation(transformation);
        m.setTransformationParameter(parameter);
        rescore(m, sourceColumn, targetColumn, sourceDb, targetDb);
        m.setStatus(MappingStatus.MODIFIED);
        m.setOrigin(ColumnMapping.ORIGIN_USER);
        m.setDecidedAt(Instant.now());
    }

    private void rescore(ColumnMapping m, ColumnMetadata s, ColumnMetadata t, DatabaseType sourceDb,
                         DatabaseType targetDb) {
        ScoreBreakdown breakdown = engine.scorePair(s, t, sourceDb, targetDb, m.getTransformation());
        MappingEngine.applyScore(m, breakdown);
    }

    // ------------------------------------------------------------------ validation and approval

    public ValidationReport validate(String projectId) {
        return projects.modify(projectId, project -> {
            ValidationReport report = validator.validate(project);
            project.setLastValidation(report);
            if (!report.valid() && project.hasMappings()) {
                project.invalidateApproval();
                project.transition(ProjectState.MAPPING_VALIDATION_FAILED,
                        report.errors() + " validation error(s)");
            } else if (report.valid() && project.getState() == ProjectState.MAPPING_VALIDATION_FAILED) {
                project.transition(ProjectState.MAPPING_REVIEW_REQUIRED, "Validation passed; waiting for approval");
            }
            projects.save(project);
            audit.info("Mapping validated project={} version={} valid={} errors={} warnings={}", projectId,
                    project.getMappingVersion(), report.valid(), report.errors(), report.warnings());
            return report;
        });
    }

    /**
     * Records the user's explicit approval. The server validates again, checks that the databases still match
     * the snapshot the mapping was built on, and only then stores the approval.
     */
    public MigrationProject approve(String projectId, int expectedVersion, boolean confirmReviewed, String user) {
        return projects.modify(projectId, project -> {
            if (expectedVersion != project.getMappingVersion()) {
                throw new ApplicationException(ErrorCode.PRJ_CONFLICT_001, "Approval requested for version "
                        + expectedVersion + " but project is at " + project.getMappingVersion());
            }
            if (!confirmReviewed) {
                throw invalid("Confirm that you have reviewed all mappings, warnings and unmapped columns.");
            }
            if (!project.hasMappings()) {
                throw state("Generate and review mapping suggestions before approving.");
            }
            ValidationReport report = validator.validate(project);
            project.setLastValidation(report);
            if (!report.valid()) {
                project.invalidateApproval();
                project.transition(ProjectState.MAPPING_VALIDATION_FAILED, report.errors() + " validation error(s)");
                projects.save(project);
                throw new ApplicationException(ErrorCode.MAP_VAL_002, "Approval refused: " + report.errors()
                        + " validation error(s)", firstErrors(report));
            }
            DiscoveryService.Drift drift = discovery.detectDrift(project);
            if (drift.changed()) {
                throw new ApplicationException(ErrorCode.MAP_META_001, "Metadata drift at approval: "
                        + drift.changedTables(), drift.changedTables());
            }
            ConnectionProfile source = project.connection(ConnectionRole.SOURCE);
            ConnectionProfile target = project.connection(ConnectionRole.TARGET);
            project.setApproval(new ApprovalRecord(Instant.now(), user, project.getId(), project.getName(),
                    project.getMappingVersion(), project.mappingHash(), drift.liveFingerprint(), source.display(),
                    target.display()));
            project.setPreviewVerifiedAt(null);
            project.transition(ProjectState.MAPPING_APPROVED, "Approved by " + user);
            projects.save(project);
            audit.info("Mapping APPROVED project={} version={} by={} warnings={}", projectId,
                    project.getMappingVersion(), user, report.warnings());
            return project;
        });
    }

    static List<String> firstErrors(ValidationReport report) {
        List<String> messages = new ArrayList<>(report.issues().stream().filter(ValidationIssue::isError)
                .map(ValidationIssue::message).limit(10).toList());
        if (report.errors() > messages.size()) {
            messages.add("... and " + (report.errors() - messages.size()) + " more. See the validation report.");
        }
        return messages;
    }

    // ------------------------------------------------------------------ helpers

    private static TablePairMapping requirePair(MigrationProject project, String pairId) {
        return project.pair(pairId == null ? "" : pairId).orElseThrow(() ->
                invalid("The table pair was not found in this project."));
    }

    private static TableMetadata snapshot(MigrationProject project, ConnectionRole role, TablePairMapping pair) {
        String key = (role == ConnectionRole.SOURCE ? pair.getSourceTable() : pair.getTargetTable()).key();
        TableMetadata table = project.metadata(role).get(key);
        if (table == null) {
            throw state("The stored structure of " + key + " is missing. Select the tables again.");
        }
        return table;
    }

    private static DatabaseType dbType(MigrationProject project, ConnectionRole role) {
        ConnectionProfile profile = project.connection(role);
        if (profile == null) {
            throw state("The " + role.name().toLowerCase() + " connection is missing.");
        }
        return profile.type();
    }

    private static ApplicationException invalid(String message) {
        return new ApplicationException(ErrorCode.CFG_VAL_001, message, List.of(message));
    }

    private static ApplicationException state(String message) {
        return new ApplicationException(ErrorCode.PRJ_STATE_001, message, List.of(message));
    }
}
